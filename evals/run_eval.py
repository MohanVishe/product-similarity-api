"""Retrieval eval: labelled queries -> the API's own search code -> metrics.

Indexes the catalogue into an in-process (ephemeral) Chroma with the same
code ingest.py uses, runs every query in evals/queries.json through
retrieval.search (what /similar_products calls), and writes
evals/results.json and evals/RESULTS.md. No Chroma server needed.

    python -m evals.run_eval            # regenerate results.json + RESULTS.md
    python -m evals.run_eval --check    # fail if numbers drift from the committed files
"""
import argparse
import json
import sys
from importlib.metadata import version
from pathlib import Path

import chromadb
import pandas as pd
from chromadb.config import Settings

import retrieval
from evals.scoring import by_type, first_relevant_rank, pick_floor, separation, summarize

ROOT = Path(__file__).resolve().parent.parent
HERE = Path(__file__).resolve().parent
CSV = ROOT / "data" / "Generated_Product_Data.csv"
QUERIES = HERE / "queries.json"
RESULTS_JSON = HERE / "results.json"
RESULTS_MD = HERE / "RESULTS.md"

K_VALUES = (1, 3, 5)
LIMIT = 3  # the API's default `limit`
FLOORS = [None] + [round(0.05 * i, 2) for i in range(0, 13)]  # none, 0.00 .. 0.60
MAX_RECALL_LOSS = 0.05
SIM_TOLERANCE = 0.002  # per-query similarities may wobble in the 3rd decimal across CPUs


def _identity(text):
    return text


def run_queries(collection, queries, n_products, preprocess):
    records = []
    for q in queries:
        filters = q.get("filters", {})
        full = retrieval.search(collection, q["query"], limit=n_products, preprocess=preprocess, **filters)
        # The eval ranks the whole (filtered) catalogue so MRR is defined; check that
        # its top LIMIT is exactly what the API's default call returns.
        api_default = retrieval.search(collection, q["query"], limit=LIMIT, preprocess=preprocess, **filters)
        if [r["Product Name"] for r in api_default] != [r["Product Name"] for r in full[:LIMIT]]:
            raise RuntimeError(f"{q['id']}: limit={LIMIT} and full-ranking results disagree")
        ranking = [[r["Product Name"], r["similarity"]] for r in full]
        records.append(
            {
                "id": q["id"],
                "type": q["type"],
                "query": q["query"],
                "filters": filters,
                "relevant": q["relevant"],
                "excluded": q.get("excluded", []),
                "first_relevant_rank": first_relevant_rank([n for n, _ in ranking], q["relevant"])
                if q["relevant"] else None,
                "ranking": ranking,
            }
        )
    return records


def evaluate():
    queries = json.loads(QUERIES.read_text(encoding="utf-8"))["queries"]
    frame = pd.read_csv(CSV)
    client = chromadb.EphemeralClient(settings=Settings(anonymized_telemetry=False, allow_reset=True))

    api_coll = retrieval.create_collection(client, "eval_api_pipeline", reset=True)
    n_products = retrieval.index_products(api_coll, frame)
    records = run_queries(api_coll, queries, n_products, retrieval.preprocess_text)

    # Ablation the audit asked for: the same model with no text normalisation at all.
    raw_coll = retrieval.create_collection(client, "eval_raw_text", reset=True)
    retrieval.index_products(raw_coll, frame, preprocess=_identity)
    raw_records = run_queries(raw_coll, queries, n_products, _identity)

    sweep = [summarize(records, floor, K_VALUES, LIMIT) for floor in FLOORS]
    counts = {}
    for q in queries:
        counts[q["type"]] = counts.get(q["type"], 0) + 1

    return {
        "about": "Generated by `python -m evals.run_eval`. Do not edit by hand; "
                 "`python -m evals.run_eval --check` fails if this drifts.",
        "config": {
            "embedding_model": retrieval.EMBED_MODEL,
            "distance": "cosine (similarity = 1 - distance, rounded to 3 dp as the API returns it)",
            "n_products": n_products,
            "n_queries": len(queries),
            "queries_by_type": counts,
            "k_values": list(K_VALUES),
            "limit": LIMIT,
            "api_default_min_similarity": retrieval.DEFAULT_MIN_SIMILARITY,
            "floor_rule": f"lowest off-topic FP rate among floors costing at most "
                          f"{MAX_RECALL_LOSS} recall@{LIMIT} vs no floor; ties -> lowest floor",
        },
        "at_api_default": summarize(records, retrieval.DEFAULT_MIN_SIMILARITY, K_VALUES, LIMIT),
        "no_floor_by_type": by_type(records, None, K_VALUES),
        "sweep": sweep,
        "separation_no_floor": separation(records, LIMIT),
        "floor_picked_by_rule": pick_floor(sweep, MAX_RECALL_LOSS, LIMIT),
        "ablation_raw_text": {
            "note": "Same model and queries, descriptions and queries embedded without preprocess_text.",
            "no_floor": summarize(raw_records, None, K_VALUES, LIMIT),
            "no_floor_by_type": by_type(raw_records, None, K_VALUES),
        },
        "queries": records,
    }


def _environment():
    return {pkg: version(pkg) for pkg in ("chromadb", "sentence-transformers", "torch", "transformers", "nltk")}


def _fmt(value):
    if value is None:
        return "none"
    if isinstance(value, float):
        return f"{value:.3f}"
    return str(value)


def render_markdown(results):
    cfg = results["config"]
    head = results["at_api_default"]
    limit = cfg["limit"]
    lines = [
        "# Retrieval eval results",
        "",
        "_Generated by `python -m evals.run_eval` from [`queries.json`](queries.json); "
        "numbers in [`results.json`](results.json). Do not edit by hand — CI runs "
        "`python -m evals.run_eval --check`._",
        "",
        f"- Catalogue: {cfg['n_products']} products · model `{cfg['embedding_model']}` · {cfg['distance']}",
        f"- Queries: {cfg['n_queries']} ("
        + ", ".join(f"{t} {n}" for t, n in cfg["queries_by_type"].items())
        + "), labelled by the author from the product rows. Small and author-written: "
          "these numbers describe this catalogue, not general retrieval quality.",
        f"- Every query goes through `retrieval.search`, the function `/similar_products` calls, "
        f"against an in-process Chroma indexed by `retrieval.index_products` (what `ingest.py` runs).",
        "",
        f"## At the API default (`min_similarity` = {_fmt(cfg['api_default_min_similarity'])}, `limit` = {cfg['limit']})",
        "",
        "| Metric | Value | n |",
        "|---|---|---|",
    ]
    for k in cfg["k_values"]:
        lines.append(f"| recall@{k} | {_fmt(head[f'recall@{k}'])} | {head['n_on_topic']} on-topic |")
    lines += [
        f"| MRR | {_fmt(head['mrr'])} | {head['n_on_topic']} on-topic |",
        f"| off-topic queries returning ≥1 product | {_fmt(head['off_topic_fp_rate'])} | {head['n_off_topic']} off-topic |",
        f"| negation: ruled-out product ranked 1st | {_fmt(head['negation_excluded_at_1'])} | {head['n_negation_with_excluded']} |",
        f"| negation: ruled-out product in top {limit} | {_fmt(head[f'negation_excluded_in_top{limit}'])} | {head['n_negation_with_excluded']} |",
        "",
        "## By query type (no floor)",
        "",
        "| Type | n | " + " | ".join(f"recall@{k}" for k in cfg["k_values"]) + " | MRR |",
        "|---|---|" + "---|" * len(cfg["k_values"]) + "---|",
    ]
    for query_type, row in results["no_floor_by_type"].items():
        lines.append(
            f"| {query_type} | {row['n']} | "
            + " | ".join(_fmt(row[f"recall@{k}"]) for k in cfg["k_values"])
            + f" | {_fmt(row['mrr'])} |"
        )
    lines += [
        "",
        "## `min_similarity` sweep",
        "",
        "What the API would return at each floor (top "
        f"{cfg['limit']}). The off-topic column is the false-positive rate: the share of "
        "off-topic queries that still get at least one product back.",
        "",
        f"| min_similarity | recall@{cfg['limit']} | MRR | on-topic queries returning nothing | off-topic FP rate |",
        "|---|---|---|---|---|",
    ]
    for row in results["sweep"]:
        lines.append(
            f"| {_fmt(row['min_similarity'])} | {_fmt(row[f'recall@{limit}'])} | "
            f"{_fmt(row['mrr'])} | {_fmt(row['on_topic_empty_rate'])} | {_fmt(row['off_topic_fp_rate'])} |"
        )
    sep = results["separation_no_floor"]
    lines += [
        "",
        f"Separation (no floor): the best off-topic score is **{_fmt(sep['off_topic_best_similarity_max'])}**; "
        f"the weakest first correct hit of an on-topic query is **{_fmt(sep['on_topic_first_relevant_similarity_min'])}**; "
        f"the weakest correct result inside the top {limit} is "
        f"**{_fmt(sep[f'on_topic_relevant_in_top{limit}_similarity_min'])}**.",
        "",
        f"Floor the pre-set rule would pick ({cfg['floor_rule']}): "
        f"**{_fmt(results['floor_picked_by_rule'])}**. Any floor read off this table is chosen on the "
        "same queries it is scored on, so the numbers at that floor are in-sample, not held-out.",
        "",
        "## Ablation: no text normalisation",
        "",
        results["ablation_raw_text"]["note"],
        "",
        "| Pipeline | " + " | ".join(f"recall@{k}" for k in cfg["k_values"]) + " | MRR |",
        "|---|" + "---|" * len(cfg["k_values"]) + "---|",
    ]
    no_floor = results["sweep"][0]
    raw = results["ablation_raw_text"]["no_floor"]
    for label, row in (("API (preprocess_text)", no_floor), ("raw text", raw)):
        lines.append(
            f"| {label} | " + " | ".join(_fmt(row[f"recall@{k}"]) for k in cfg["k_values"])
            + f" | {_fmt(row['mrr'])} |"
        )
    lines += [
        "",
        f"## Misses (on-topic queries with no relevant product in the top {cfg['limit']}, no floor)",
        "",
    ]
    misses = [
        r for r in results["queries"]
        if r["relevant"] and (r["first_relevant_rank"] is None or r["first_relevant_rank"] > cfg["limit"])
    ]
    if not misses:
        lines.append("None.")
    else:
        lines += ["| id | query | relevant | first relevant rank | top 3 returned |", "|---|---|---|---|---|"]
        for r in misses:
            top = ", ".join(f"{n} ({s:.3f})" for n, s in r["ranking"][:3])
            lines.append(
                f"| {r['id']} | {r['query']} | {', '.join(r['relevant'])} | "
                f"{_fmt(r['first_relevant_rank'])} | {top} |"
            )
    lines += [
        "",
        "## Negation queries (no floor)",
        "",
        "| id | query | ruled out | top 3 returned |",
        "|---|---|---|---|",
    ]
    for r in results["queries"]:
        if r["type"] == "negation":
            top = ", ".join(f"{n} ({s:.3f})" for n, s in r["ranking"][:3])
            lines.append(f"| {r['id']} | {r['query']} | {', '.join(r['excluded']) or '—'} | {top} |")
    lines += [
        "",
        "## Off-topic queries: best similarity",
        "",
        "| id | query | top product (similarity) |",
        "|---|---|---|",
    ]
    for r in results["queries"]:
        if r["type"] == "off_topic":
            name, sim = r["ranking"][0]
            lines.append(f"| {r['id']} | {r['query']} | {name} ({sim:.3f}) |")
    lines += ["", "## Environment of the committed run", ""]
    for pkg, ver in results.get("environment", {}).items():
        lines.append(f"- {pkg} {ver}")
    return "\n".join(lines) + "\n"


def _compare(new, old, path="", tol=1e-9, errors=None):
    errors = [] if errors is None else errors
    if path.startswith("queries"):
        tol = SIM_TOLERANCE
    if isinstance(new, dict) and isinstance(old, dict):
        for key in sorted(set(new) | set(old)):
            if key not in new or key not in old:
                errors.append(f"{path}.{key}: present in only one of new/committed")
            else:
                _compare(new[key], old[key], f"{path}.{key}" if path else key, tol, errors)
    elif isinstance(new, list) and isinstance(old, list):
        if len(new) != len(old):
            errors.append(f"{path}: length {len(new)} != committed {len(old)}")
        for i, (a, b) in enumerate(zip(new, old)):
            _compare(a, b, f"{path}[{i}]", tol, errors)
    elif isinstance(new, float) and isinstance(old, (int, float)) and not isinstance(old, bool):
        if abs(new - old) > tol:
            errors.append(f"{path}: {new} != committed {old}")
    elif new != old:
        errors.append(f"{path}: {new!r} != committed {old!r}")
    return errors


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare against the committed results; exit 1 on drift")
    args = ap.parse_args()

    results = evaluate()
    head = results["at_api_default"]
    print(
        f"{results['config']['n_queries']} queries | recall@1 {_fmt(head['recall@1'])} "
        f"recall@3 {_fmt(head['recall@3'])} MRR {_fmt(head['mrr'])} "
        f"off-topic FP {_fmt(head['off_topic_fp_rate'])} (min_similarity={_fmt(head['min_similarity'])}) "
        f"| floor by rule: {_fmt(results['floor_picked_by_rule'])}"
    )

    if args.check:
        committed = json.loads(RESULTS_JSON.read_text(encoding="utf-8"))
        committed_env = committed.pop("environment", None)
        errors = _compare(results, committed)
        committed["environment"] = committed_env
        if RESULTS_MD.read_text(encoding="utf-8") != render_markdown(committed):
            errors.append("RESULTS.md does not match what results.json renders to (edited by hand?)")
        if errors:
            print(f"DRIFT: {len(errors)} difference(s) from the committed results", file=sys.stderr)
            for e in errors[:50]:
                print("  " + e, file=sys.stderr)
            sys.exit(1)
        print("check OK: results match the committed results.json and RESULTS.md")
        return

    results["environment"] = _environment()
    RESULTS_JSON.write_text(json.dumps(results, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    RESULTS_MD.write_text(render_markdown(results), encoding="utf-8")
    print(f"wrote {RESULTS_JSON.relative_to(ROOT)} and {RESULTS_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
